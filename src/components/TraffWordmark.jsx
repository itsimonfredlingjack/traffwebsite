/**
 * The wordmark is the logo: "Träff" in outlines, with the yellow pen.
 * Paths come from docs/brand/traff-wordmark.svg, so the logo loads no font.
 */
export default function TraffWordmark({
  pen = true,
  height = 26,
  title = 'Träff',
  decorative = false,
  draw = false,
  className = '',
}) {
  const width = (height * VIEW_W) / VIEW_H;
  const labelled = !decorative;
  return (
    <span
      className={`traff-wordmark${draw ? ' traff-wordmark--draw' : ''}${className ? ` ${className}` : ''}`}
      style={{ width, height }}
      role={labelled ? 'img' : undefined}
      aria-label={labelled ? title : undefined}
      aria-hidden={decorative ? 'true' : undefined}
    >
      <svg viewBox="-160 -860 3011 980" width={width} height={height} aria-hidden="true" focusable="false">
        {pen && (
          <g className="traff-wordmark-pen">
            <path
              d={PEN_D}
              fill="var(--strykgul)"
              fillOpacity="0.92"
              stroke="var(--strykgul)"
              strokeOpacity="0.92"
              strokeWidth="10"
              strokeLinejoin="round"
              transform={PEN_TRANSFORM}
              style={{ mixBlendMode: 'multiply' }}
            />
          </g>
        )}
        {LETTERS.map((letter, index) => (
          <path key={index} d={letter.d} transform={letter.transform} fill="var(--ink)" />
        ))}
      </svg>
    </span>
  );
}
